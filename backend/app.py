# Active jobs: {job_id: {'queue': Queue, 'status': str, 'filename': str, 'event': Event, 'start_time': float}}
JOBS = {}
JOBS_LOCK = threading.Lock()

def cleanup_stale_jobs():
    """Background task to remove jobs older than 1 hour to prevent memory leaks."""
    while True:
        time.sleep(600)  # Run every 10 minutes
        now = time.time()
        with JOBS_LOCK:
            stale_ids = [jid for jid, info in JOBS.items() if now - info.get('start_time', 0) > 3600]
            for jid in stale_ids:
                event = JOBS[jid].get("event")
                if event:
                    event.set()
                del JOBS[jid]

_cleanup_started = False

@app.before_request
def _start_cleanup_once():
    """Lazy-start cleanup thread on first request — compatible with Gunicorn pre-fork workers."""
    global _cleanup_started
    if not _cleanup_started:
        _cleanup_started = True
        threading.Thread(target=cleanup_stale_jobs, daemon=True).start()


# ──────────────────────────────────────────────
# Ephemeral local session authentication (generated by Electron per launch).
# ──────────────────────────────────────────────
AUTH_KEY = settings.auth_key

def check_auth(f):
    """Require the per-launch token without persisting it or putting it in URLs."""
    @wraps(f)
    def decorated(*args, **kwargs):
        if request.method == "OPTIONS":
            return Response(status=204)
        if not AUTH_KEY:
            return f(*args, **kwargs)
        provided = request.headers.get("X-Local-Session", "")
        if not provided or not hmac.compare_digest(provided, AUTH_KEY):
            return jsonify({"success": False, "error": "Sesi lokal tidak valid."}), 401
        return f(*args, **kwargs)
    return decorated


