@app.after_request
def add_api_cors_headers(response):
    """Allow the separately hosted frontend to call only configured API origins."""
    origin = request.headers.get("Origin", "").rstrip("/")
    desktop_origin = settings.desktop_mode and origin == "null"
    if request.path.startswith("/api/") and (origin in settings.frontend_origins or desktop_origin):
        response.headers["Access-Control-Allow-Origin"] = origin
        response.headers["Access-Control-Allow-Credentials"] = "true"
        response.headers["Vary"] = "Origin"
        response.headers["Access-Control-Allow-Headers"] = "Content-Type, X-Local-Session"
        response.headers["Access-Control-Allow-Methods"] = "GET, POST, DELETE, OPTIONS"
    return response


