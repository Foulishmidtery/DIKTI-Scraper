@app.route("/api/run-scraper", methods=["POST"])
@check_auth
def api_run_scraper():
    """Start scraper untuk subset prodi yang dipilih user dari whitelist 21 prodi."""
    from backend.database import create_scrape_run, database_status
    from scraper.target_prodi import TARGET_PRODI_NAMES

    payload = request.get_json(silent=True) or {}
    requested = payload.get("prodi", [])
    if not isinstance(requested, list):
        return jsonify({"success": False, "error": "Field 'prodi' harus berupa list."}), 400

    allowed_map = {str(name).strip().upper(): str(name).strip() for name in TARGET_PRODI_NAMES}
    prodi_keywords = []
    invalid = []
    seen = set()

    for raw_name in requested:
        key = str(raw_name or "").strip().upper()
        if not key:
            continue
        if key not in allowed_map:
            invalid.append(str(raw_name))
            continue
        canonical = allowed_map[key]
        if canonical.upper() not in seen:
            seen.add(canonical.upper())
            prodi_keywords.append(canonical)

    if invalid:
        return jsonify({
            "success": False,
            "error": "Ada prodi di luar daftar yang diizinkan.",
            "invalid": invalid,
        }), 400

    if not prodi_keywords:
        return jsonify({
            "success": False,
            "error": "Pilih minimal 1 program studi sebelum menjalankan scraper."
        }), 400

    job_id = str(uuid.uuid4())
    database = database_status()
    if not database["connected"]:
        return jsonify({
            "success": False,
            "error": f"PostgreSQL belum siap: {database['message']}",
        }), 503
    try:
        create_scrape_run(job_id, prodi_keywords)
    except Exception as e:
        app.logger.exception("create scrape run failed")
        return jsonify({"success": False, "error": "Gagal membuat job di PostgreSQL. Periksa konfigurasi dan log backend."}), 503

    q = queue.Queue()
    stop_event = threading.Event()
    with JOBS_LOCK:
        JOBS[job_id] = {
            "queue": q,
            "status": "running",
            "filename": None,
            "event": stop_event,
            "start_time": time.time(),
            "selected_prodi": list(prodi_keywords),
        }

    def worker():
        from backend.database import (
            complete_scrape_run,
            export_database,
            fail_scrape_run,
            persist_scrape_results,
        )
        from scraper.dosen_scraper import collect_dosen_data
        from scraper.fetch_prodi import fetch_target_prodi_catalog
        data_persisted = False
        try:
            def cb(msg):
                if isinstance(msg, dict) and msg.get("__progress__"):
                    try:
                        q.put({"type": "progress", "step": msg["step"], "current": msg["current"],
                               "total": msg["total"], "label": msg["label"]}, block=False)
                    except queue.Full:
                        pass
                    return
                try:
                    q.put({"type": "log", "message": str(msg)}, block=False)
                except queue.Full:
                    pass

            cb(f"🎯 Prodi dipilih: {len(prodi_keywords)} dari {len(TARGET_PRODI_NAMES)} prodi tersedia")
            for name in prodi_keywords:
                cb(f"   ✓ {name}")

            # Auto-sync katalog hanya untuk prodi yang dipilih user.
            catalog = fetch_target_prodi_catalog(
                prodi_keywords, callback=cb, stop_event=stop_event
            )
            canonical = {
                str(item.get("target_name", "")).strip().upper():
                str(item.get("nama_prodi", "")).strip()
                for item in catalog
                if item.get("target_name") and item.get("nama_prodi")
            }
            scrape_targets = [canonical.get(name.upper(), name) for name in prodi_keywords]
            cb(f"🚀 Memulai scraping {len(scrape_targets)} prodi terpilih...\n")

            profiles, prodi_list, _semester = collect_dosen_data(
                scrape_targets, cb, stop_event
            )

            cb({"__progress__": True, "step": 4, "current": 0, "total": 1, "label": "Cek & simpan PostgreSQL"})
            cb("\n🗄️ Memeriksa hasil scraping terhadap data PostgreSQL...")
            stats = persist_scrape_results(job_id, profiles, prodi_list)
            data_persisted = True
            cb(
                f"✅ Dosen baru: {stats['dosen_inserted']}, "
                f"diperbarui: {stats.get('dosen_updated', 0)}, "
                f"tanpa perubahan: {stats['dosen_skipped']}"
            )
            cb(
                f"✅ Prodi baru: {stats['prodi_inserted']}, "
                f"diperbarui: {stats.get('prodi_updated', 0)}, "
                f"tanpa perubahan: {stats['prodi_skipped']}"
            )
            cb({"__progress__": True, "step": 4, "current": 1, "total": 1, "label": "PostgreSQL tersimpan"})

            filename = None
            if settings.auto_export:
                def export_cb(message):
                    if isinstance(message, dict) and message.get("__progress__"):
                        message = {**message, "step": 5, "label": "Export dari PostgreSQL"}
                    cb(message)

                cb({"__progress__": True, "step": 5, "current": 0, "total": 1, "label": "Export dari PostgreSQL"})
                filename = export_database(OUTPUT_DIR, export_cb)
            # Secure gateway menyelesaikan status job secara atomik pada batch
            # terakhir. Mode database langsung tetap memakai finalisasi lokal.
            if not settings.secure_gateway:
                complete_scrape_run(job_id, filename)
            with JOBS_LOCK:
                if job_id in JOBS:
                    JOBS[job_id]["status"] = "done"
                    JOBS[job_id]["filename"] = filename
                    JOBS[job_id]["stats"] = stats
            q.put({"type": "done", "filename": filename, "stats": stats})
        except Exception as e:
            fail_scrape_run(job_id, e)
            with JOBS_LOCK:
                if job_id in JOBS:
                    JOBS[job_id]["status"] = "error"
            message = (
                "Data sudah tersimpan di PostgreSQL, tetapi status riwayat gagal diperbarui."
                if data_persisted else
                "Proses scraping gagal. Silakan coba kembali."
            )
            q.put({"type": "error", "message": message})
        finally:
            q.put(None)

    t = threading.Thread(target=worker, daemon=True)
    t.start()
    return jsonify({
        "success": True,
        "job_id": job_id,
        "selected_total": len(prodi_keywords),
        "selected_prodi": prodi_keywords,
    })


@app.route("/api/stop-scraper/<job_id>", methods=["POST"])
@check_auth
def api_stop_scraper(job_id):
    """Stop an active scraping job."""
    from backend.database import cancel_scrape_run

    found = False
    with JOBS_LOCK:
        if job_id in JOBS and JOBS[job_id].get("event"):
            JOBS[job_id]["event"].set()
            JOBS[job_id]["status"] = "cancelled"
            found = True
    if found:
        cancel_scrape_run(job_id)
        return jsonify({"success": True, "message": "Scraping dibatalkan"})
    return jsonify({"success": False, "error": "Job tidak ditemukan atau sudah selesai"}), 404


@app.route("/api/stream/<job_id>")
@check_auth
def api_stream(job_id):
    """SSE endpoint to stream scraping logs."""
    with JOBS_LOCK:
        if job_id not in JOBS:
            return jsonify({"error": "Job not found"}), 404
        q = JOBS[job_id]["queue"]

    def generate():
        try:
            yield "data: {\"type\": \"connected\"}\n\n"
            while True:
                try:
                    # Heartbeat setiap 30s untuk menghindari Nginx/proxy timeout default 60s
                    msg = q.get(timeout=30)
                    if msg is None:
                        break
                    yield f"data: {json.dumps(msg)}\n\n"
                except queue.Empty:
                    yield "data: {\"type\": \"heartbeat\"}\n\n"
        finally:
            # DO NOT DELETE FROM JOBS! If the SSE stream disconnects, 
            # the background worker should continue running.
            pass

    return Response(
        generate(),
        content_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


