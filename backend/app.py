@app.route("/api/session", methods=["POST", "DELETE"])
@check_auth
def api_session():
    """Activate or revoke the short-lived remote gateway session."""
    if not settings.secure_gateway:
        return jsonify({"success": True, "security": {"mode": "development", "required": False, "authenticated": True}})
    from backend.secure_gateway import GatewayError, gateway_client

    if request.method == "DELETE":
        gateway_client.close()
        return jsonify({"success": True})
    payload = request.get_json(silent=True) or {}
    code = payload.get("activation_code", "")
    if not isinstance(code, str):
        return jsonify({"success": False, "error": "Kode aktivasi tidak valid."}), 400
    try:
        return jsonify({"success": True, "security": gateway_client.activate(code)})
    except GatewayError as error:
        message = str(error)
        status = 401 if message == "Kode aktivasi tidak valid." else 503
        return jsonify({"success": False, "error": message}), status


